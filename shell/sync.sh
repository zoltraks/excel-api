#!/usr/bin/env bash
set -euo pipefail

SOURCE="docs/contract/openapi.yaml"
MARKER="# GENERATED from docs/contract/openapi.yaml - do not edit"

TARGETS=(
  "excel-api-node/resources/openapi.yaml"
  "excel-api-java/src/main/resources/openapi.yaml"
  "excel-api-csharp/src/ExcelApi/Resources/openapi.yaml"
  "excel-api-rust/resources/openapi.yaml"
)

if [[ ! -f "$SOURCE" ]]; then
  echo "Source file not found: $SOURCE" >&2
  exit 1
fi

VERSION=$(LC_ALL=C grep -m1 -E '^  version:' "$SOURCE" | sed -E 's/^  version:[[:space:]]*"?([^"]+)"?/\1/' | tr -d '[:space:]')
if [[ -z "$VERSION" ]]; then
  echo "Could not extract info.version from $SOURCE" >&2
  exit 1
fi
echo "Contract version: $VERSION"

for target in "${TARGETS[@]}"; do
  mkdir -p "$(dirname "$target")"
  if [[ -f "$target" ]] && printf '%s\n' "$MARKER" | cat - "$SOURCE" | sha256sum | cut -d' ' -f1 | grep -q "$(sha256sum "$target" | cut -d' ' -f1)"; then
    echo "  [OK] $target (up to date)"
    continue
  fi
  { printf '%s\n' "$MARKER"; cat "$SOURCE"; } > "$target"
  echo "  [SYNC] $target"
done

python3 - "$VERSION" <<'PYEOF'
import json, re, sys

version = sys.argv[1]

def set_json_version(path):
    with open(path) as f:
        data = json.load(f)
    changed = False
    if data.get("version") != version:
        data["version"] = version
        changed = True
    root_pkg = data.get("packages", {}).get("")
    if root_pkg is not None and root_pkg.get("version") != version:
        root_pkg["version"] = version
        changed = True
    if changed:
        with open(path, "w") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
        print(f"  [VER] {path} -> {version}")
    else:
        print(f"  [OK] {path}")

set_json_version("excel-api-node/package.json")
set_json_version("excel-api-node/package-lock.json")
set_json_version("excel-api-test/package.json")
set_json_version("excel-api-test/package-lock.json")

def rewrite(path, pattern, repl):
    with open(path) as f:
        text = f.read()
    new = re.sub(pattern, repl, text, count=1)
    if new != text:
        with open(path, "w") as f:
            f.write(new)
        print(f"  [VER] {path} -> {version}")
    else:
        print(f"  [OK] {path}")

rewrite(
    "excel-api-java/pom.xml",
    r"(<artifactId>excel-api</artifactId>\s*<version>)[^<]+",
    lambda m: m.group(1) + version,
)
rewrite(
    "excel-api-csharp/src/ExcelApi/ExcelApi.csproj",
    r"<Version>[^<]+</Version>",
    f"<Version>{version}</Version>",
)
rewrite(
    "excel-api-rust/Cargo.toml",
    r'(?m)^version = "[^"]+"',
    f'version = "{version}"',
)

go_file = "excel-api-go/internal/config/version.go"
with open(go_file) as f:
    go_text = f.read()
go_new = re.sub(
    r'const Version = "[^"]+"',
    f'const Version = "{version}"',
    go_text,
)
if "// Code generated by shell/sync.sh; DO NOT EDIT" not in go_new:
    go_new = go_new.replace(
        "package config\n",
        "package config\n\n// Code generated by shell/sync.sh; DO NOT EDIT.\n",
        1,
    )
if go_new != go_text:
    with open(go_file, "w") as f:
        f.write(go_new)
    print(f"  [VER] {go_file} -> {version}")
else:
    print(f"  [OK] {go_file}")
PYEOF
